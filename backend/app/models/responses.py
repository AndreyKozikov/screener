"""Модели ответов API.

Этот модуль содержит модели данных для структурированных ответов API,
включая успешные ответы со списками данных и ответы об ошибках.
Используется для стандартизации формата ответов всех эндпоинтов приложения.
"""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel

from .bonds_dto import BondScreenerDTO
from .kbd_DTO import KbdDTO, KbdDataResponse


class BondsListResponse(BaseModel):
    """Модель ответа API для эндпоинта получения списка облигаций.

    Используется для возврата отфильтрованного и отпагинированного списка
    облигаций с метаданными о количестве записей. Содержит информацию
    для корректной работы пагинации на фронтенде. Элементы списка bonds —
    легковесные DTO (BondScreenerDTO) только с полями для таблицы скринера.

    Attributes:
        total: Общее количество облигаций в базе данных (до применения фильтров).
        filtered: Количество облигаций после применения всех фильтров.
        skip: Количество пропущенных записей (параметр пагинации из запроса).
        limit: Максимальное количество записей в ответе (параметр пагинации из запроса).
        bonds: Список объектов BondScreenerDTO с данными об облигациях.
            Количество элементов в списке не превышает значение limit.

    Examples:
        Пример ответа для запроса первой страницы из 50 записей:

        >>> response = BondsListResponse(
        ...     total=1000,
        ...     filtered=250,
        ...     skip=0,
        ...     limit=50,
        ...     bonds=[...]  # список из 50 BondScreenerDTO
        ... )
    """
    total: int
    filtered: int
    skip: int
    limit: int
    bonds: List[BondScreenerDTO]


class ColumnMapping(BaseModel):
    """Модель маппинга названий колонок.
    
    Используется для перевода технических названий полей облигаций
    на человекочитаемые названия для отображения на фронтенде.
    
    Attributes:
        field_name: Техническое название поля (например, "COUPONPERCENT").
        display_name: Отображаемое название поля на русском языке
            (например, "Доходность купона").
    
    Examples:
        >>> mapping = ColumnMapping(
        ...     field_name="COUPONPERCENT",
        ...     display_name="Доходность купона"
        ... )
    """
    field_name: str
    display_name: str


class DescriptionItem(BaseModel):
    """Модель описания поля облигации.
    
    Используется для предоставления детальной информации о полях облигаций
    на фронтенде, включая описание назначения поля и его тип данных.
    
    Attributes:
        field_name: Техническое название поля (например, "COUPONPERCENT").
        title: Краткое название поля для отображения (например, "Доходность купона").
        description: Подробное описание поля и его назначения (опционально).
            Может содержать информацию о единицах измерения, диапазоне значений и т.д.
        type: Тип данных поля (опционально). Например, "float", "date", "string".
    
    Examples:
        >>> desc = DescriptionItem(
        ...     field_name="COUPONPERCENT",
        ...     title="Доходность купона",
        ...     description="Процентная ставка купона облигации в процентах",
        ...     type="float"
        ... )
    """
    field_name: str
    title: str
    description: Optional[str] = None
    type: Optional[str] = None


class ErrorResponse(BaseModel):
    """Модель ответа API при возникновении ошибки.
    
    Используется для стандартизации формата ответов об ошибках во всех
    эндпоинтах приложения. Позволяет фронтенду единообразно обрабатывать
    различные типы ошибок.
    
    Attributes:
        detail: Детальное описание ошибки на русском языке.
            Содержит информацию о том, что пошло не так и как это исправить.
        error_code: Код ошибки для программной обработки (опционально).
            Используется для идентификации типа ошибки на фронтенде
            и применения соответствующей логики обработки.
            Примеры: "VALIDATION_ERROR", "NOT_FOUND", "INTERNAL_ERROR".
    
    Examples:
        Пример ответа при ошибке валидации:
        
        >>> error = ErrorResponse(
        ...     detail="Некорректное значение параметра coupon_min: должно быть от 0 до 100",
        ...     error_code="VALIDATION_ERROR"
        ... )
        
        Пример ответа при отсутствии ресурса:
        
        >>> error = ErrorResponse(
        ...     detail="Облигация с SECID 'SU26238RMFS4' не найдена",
        ...     error_code="NOT_FOUND"
        ... )
    """
    detail: str
    error_code: Optional[str] = None
