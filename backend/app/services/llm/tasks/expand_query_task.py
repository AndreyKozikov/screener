import re
import json
from typing import Any, Dict
from app.services.llm.tasks.base import BaseAnalysisTask

QUERY_EXPANSION_PROMPT_TEMPLATE: str = """Ты — модуль обогащения пользовательского запроса для векторного поиска по конкретной облигации и определения временных рамок поиска событий.

Твоя задача:
1. Превратить вопрос пользователя в один качественный поисковый запрос для поиска по документам и событиям по облигации.
2. Определить дату, с которой необходимо искать события в ленте раскрытия информации (e-disclosure), основываясь на контексте вопроса пользователя.
3. Выделить несколько независимых поисковых фраз (search_queries), каждая из которых описывает отдельный аспект пользовательского вопроса и подходит для самостоятельного векторного поиска.

Дата начала размещения облигации на рынке: {first_date_trade} (это дата, когда облигация была впервые выпущена и начала торговаться на рынке. События до этой даты искать не имеет смысла).

Правила определения даты начала поиска событий (start_date):
- Проанализируй пользовательский запрос. Если пользователь спрашивает про события за определенный период (например, "за последний год", "в 2024 году", "за последние 3 месяца", "после мая 2025"), определи точную дату начала этого периода в формате YYYY-MM-DD.
- Если в запросе пользователя нет ограничений по времени или период не указан, верни дату начала размещения облигации: {first_date_trade}.
- Дата должна быть строго в формате YYYY-MM-DD.

При анализе вопроса выделяй:

- название эмитента;
- название выпуска;
- ISIN;
- регистрационный номер выпуска;
- тикер облигации;
- название рейтингового агентства;
- финансовые показатели;
- виды корпоративных событий;
- даты и периоды;
- юридические и финансовые термины.

Если эти сущности присутствуют в вопросе пользователя, они обязательно должны быть сохранены в expanded_query без изменений.

Правила обогащения запроса (expanded_query):
- Не отвечай на вопрос пользователя.
- Не меняй смысл вопроса.
- Если вопрос уже конкретный и профессиональный, сохрани его смысл и терминологию, только слегка нормализуй формулировку.
- Если вопрос общий, добавь типичные термины, по которым такая информация обычно находится в документах по облигации: эмитент, условия выпуска, решение о выпуске, купон, порядок определения купона, даты выплат, погашение, оферта, амортизация, существенные события, риски.
- Итоговый запрос должен быть на русском языке и подходить именно для векторного поиска по текстовым документам.
- Сформируй от 5 до 8 самостоятельных поисковых запросов длиной не более 25–40 слов каждый, каждый запрос должен описывать один отдельный аспект вопроса.
- Использовать перечисление через запятую вместо длинного предложения;
- Исключить местоимения, вводные конструкции и лишние слова;
- Запрос должен состоять преимущественно из содержательных существительных, терминов и словосочетаний.
- Не разбивай запрос на отдельные слова. Каждый элемент должен быть осмысленной фразой длиной 2–10 слов.
- Остальные элементы должны быть более узкими вариантами поиска.
- Если пользователь указал несколько тем, сформируй отдельную поисковую фразу для каждой темы.
- Используй профессиональную терминологию, встречающуюся в документах эмитентов.
- Не добавляй информацию, которой нет в вопросе пользователя.
- Не придумывай новые сущности или события.
- Избегай повторов и почти одинаковых формулировок.

Ты ДОЛЖЕН вернуть ответ СТРОГО в формате JSON со следующей структурой:
{{
  "expanded_query": [
    "первый поисковый запрос",
    "второй поисковый запрос",
    "...",
    "восьмой поисковый запрос"
  ],
  "start_date": "YYYY-MM-DD"
}}

Никакого другого текста, кроме этого JSON, возвращать нельзя. Не оборачивай JSON в markdown-блоки ```json ... ```, верни только чистый JSON-объект.

Вот вопрос пользователя, который необходимо обогатить:
{query}
"""

class ExpandQueryTask(BaseAnalysisTask):
    """Стратегия для интеллектуального расширения поисковых запросов пользователя."""

    def __init__(self, query: str) -> None:
        self.query = query

    def build_prompt(self, data: Dict[str, Any]) -> str:
        """Формирует специфичный промпт для генерации синонимов и дат."""
        return QUERY_EXPANSION_PROMPT_TEMPLATE.format(
            first_date_trade=data["first_date_trade"],
            query=self.query
        )

    def parse_response_and_validate(self, raw_text: str, **kwargs) -> Dict[str, Any]:
        """Парсит нестандартный текстовый ответ модели с помощью регулярных выражений."""

        cleaned = raw_text.strip()

        if cleaned.startswith("```"):
            cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
            cleaned = re.sub(r"\s*```$", "", cleaned)
            cleaned = cleaned.strip()

        try:
            data = json.loads(cleaned)
            expanded_query = data.get("expanded_query", [])
            start_date = data.get("start_date", "")

            return {
            "expanded_query": expanded_query,
            "start_date": start_date,
        }
        except json.JSONDecodeError:
            return {
                "expanded_query": [raw_text],
                "start_date": None,
            }

