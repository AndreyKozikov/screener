from typing import Any, List, Dict
from app.services.llm.tasks.base import BaseAnalysisTask

QA_PROMPT_TEMPLATE: str = """\
Роль: Ты — аналитик долгового рынка, эксперт по облигациям.

Задача: Используя предоставленный контекст (выдержки из эмиссионных документов и событий раскрытия), ответь на вопрос пользователя.

Правила:
1. Отвечай точно и профессионально, опираясь только на предоставленные данные.
2. Если в контексте нет ответа, так и скажи.
3. Соблюдай вежливый и деловой тон.
4. Ответ должен быть на русском языке.
5. Используй разметку Markdown для структурирования ответа (списки, жирный шрифт).
6. Математические формулы (особенно формулы расчета купона) обязательно оформляй в формате LaTeX, используя символы $...$ для строчных формул и $$...$$ для блочных.

КОНТЕКСТ (Векторный поиск):
{context}

ВОПРОС ПОЛЬЗОВАТЕЛЯ:
{query}
"""

class QuestionAnsweringTask(BaseAnalysisTask):
    """Стратегия для ответов на вопросы пользователей по контексту документов."""

    def build_prompt(self, data: Dict[str, Any]) -> str:
        """Собирает промпт для вопросов и ответов на основе переданного контекста."""

        return QA_PROMPT_TEMPLATE.format(
        context=data['vector_context'],
        query=data['queries']
    )

    def parse_response_and_validate(self, raw_text: str, **kwargs) -> str:
        """В данном случае метод возвращает простой текстовый ответ от модели."""
        return raw_text.strip()