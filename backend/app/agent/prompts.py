"""Промпты ИИ-агента подбора облигаций.

Два этапа:
1. Роутер — LLM решает: задать уточняющий вопрос (ask), вызвать инструмент
   (tool) или ответить сразу (answer).
2. Финализатор — по компактным данным инструмента пишет итоговый ответ
   в Markdown с конкретными SECID.
"""

